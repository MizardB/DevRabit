"""Conservative RCDEV CMake bootstrap, independent of SCons for host tests."""
from pathlib import Path
import re

ROOT_CMAKE = '''# Generated by RCDEV. Do not edit; see README for custom CMake.
cmake_minimum_required(VERSION 3.16)
include($ENV{IDF_PATH}/tools/cmake/project.cmake)
project(rcdev)
include("${RCDEV_DIR}/cmake/secure-spp.cmake")
'''
DEVRABIT_ROOT_CMAKE = '''# Generated by DevRabit. Do not edit; see README for custom CMake.
cmake_minimum_required(VERSION 3.16)
include($ENV{IDF_PATH}/tools/cmake/project.cmake)
project(devrabit)
include("${DEVRABIT_DIR}/cmake/secure-spp.cmake")
'''

LEGACY_SRC_CMAKE = '''# Generated by RCDEV. Do not edit; see README for custom CMake.
file(GLOB_RECURSE app_sources
    "${CMAKE_CURRENT_LIST_DIR}/*.c"
    "${CMAKE_CURRENT_LIST_DIR}/*.cpp"
    "${CMAKE_CURRENT_LIST_DIR}/*.S")
idf_component_register(SRCS ${app_sources} INCLUDE_DIRS "." REQUIRES framework-arduinoespressif32)
'''

COMPONENT_INCLUDE = 'include("$ENV{RCDEV_PLATFORM_DIR}/cmake/arduino-component.cmake")\n'
SRC_CMAKE = COMPONENT_INCLUDE + LEGACY_SRC_CMAKE.replace(
    'REQUIRES framework-arduinoespressif32', 'REQUIRES ${RCDEV_ARDUINO_COMPONENT}')

DEVRABIT_SRC_CMAKE = '''include("$ENV{DEVRABIT_PLATFORM_DIR}/cmake/arduino-component.cmake")
# Generated by DevRabit. Do not edit; see README for custom CMake.
file(GLOB_RECURSE app_sources
    "${CMAKE_CURRENT_LIST_DIR}/*.c"
    "${CMAKE_CURRENT_LIST_DIR}/*.cpp"
    "${CMAKE_CURRENT_LIST_DIR}/*.S")
idf_component_register(SRCS ${app_sources} INCLUDE_DIRS "." REQUIRES ${DEVRABIT_ARDUINO_COMPONENT})
'''

# Deliberately not a general CMake parser. Supports both RCDEV and legacy DevRabit definitions.
_ROOT = re.compile(
    r'cmake_minimum_required\(VERSION 3\.16(?:\.0)?\)\s*'
    r'include\(\$ENV\{IDF_PATH\}/tools/cmake/project\.cmake\)\s*'
    r'project\([A-Za-z0-9_-]+\)\s*'
    r'include\("\$\{(?:RCDEV_DIR|DEVRABIT_DIR)\}/cmake/secure-spp\.cmake"\)\s*'
)
# Existing example components explicitly list their sources.
_SOURCE = re.compile(
    r'include\("\$ENV\{(?:RCDEV_PLATFORM_DIR|DEVRABIT_PLATFORM_DIR)\}/cmake/arduino-component\.cmake"\)\s*'
    r'idf_component_register\(SRCS\s+(?:"[^";\n]+"\s+)+'
    r'INCLUDE_DIRS\s+"\."\s+REQUIRES\s+\$\{(?:RCDEV_ARDUINO_COMPONENT|DEVRABIT_ARDUINO_COMPONENT)\}\)\s*'
)


def arduino_component_name(package_dir):
    name = Path(package_dir).name
    if not re.fullmatch(r'[A-Za-z0-9_.+-]+', name):
        raise ValueError('RCDEV: Arduino package directory name is not CMake-compatible: '
                         + name + '. Package preserved; report the package layout. '
                         'Do not rename or delete installed packages.')
    return name


def ensure_project_files(project_dir, source_dir):
    paths = [(Path(project_dir) / 'CMakeLists.txt', ROOT_CMAKE, _ROOT, DEVRABIT_ROOT_CMAKE),
             (Path(source_dir) / 'CMakeLists.txt', SRC_CMAKE, _SOURCE, DEVRABIT_SRC_CMAKE)]
    for path, generated, pattern, legacy in paths:
        if not path.exists():
            continue
        text = path.read_text(encoding='utf-8')
        if text in (generated, legacy) or (path == paths[1][0] and text == LEGACY_SRC_CMAKE):
            continue
        stripped = re.sub(r'#[^\n]*', '', text).strip()
        if not pattern.fullmatch(stripped):
            raise ValueError(
                'RCDEV: unsupported custom CMake: %s. File preserved. '
                'Use the exact CMake contract in README (root secure-spp include '
                'AFTER project(), component resolver include and dynamic REQUIRES), '
                'or back up and remove BOTH CMakeLists.txt files yourself to '
                'regenerate them.' % path)
    for path, generated, _, legacy in paths:
        if path.exists() and path.read_text(encoding='utf-8') in (legacy, LEGACY_SRC_CMAKE):
            with path.open('w', encoding='utf-8', newline='\n') as stream:
                stream.write(generated)
        elif not path.exists():
            with path.open('x', encoding='utf-8', newline='\n') as stream:
                stream.write(generated)
